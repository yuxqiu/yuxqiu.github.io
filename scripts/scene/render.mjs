// Writes the footer scene's no-JS fallback into static/scene/: one PNG per
// layer of each scene in fallbacks() (static/js/scene/scene.js), cut out at
// frame 0, and scene.css, which sizes .scene and stacks those PNGs as CSS
// backgrounds per page (.scene[data-path=…]). When JS is on, the canvas draws
// instead and scene.css hides the backgrounds.
// Run by `make scene`, which `make build` and `make serve` depend on.

import { mkdirSync, writeFileSync } from "node:fs";
import { fallbacks, H, NARROW_MAX, NARROW_SCALE, SCALE } from "../../static/js/scene/scene.js";
import { encodePng } from "./png.mjs";
import { raster } from "./raster.mjs";

const dir = new URL("../../static/scene/", import.meta.url);
mkdirSync(dir, { recursive: true });

const scenes = fallbacks();
const written = new Set();
for (const { layers } of scenes) {
  for (const L of layers) {
    if (written.has(L.id)) continue;
    written.add(L.id);
    writeFileSync(new URL(`${L.id}.png`, dir), encodePng(L.w, H, raster(L.w, H, (fill) => L.paint(fill, L.w, 0, 0))));
  }
}

// CSS lists background layers top first. A percentage position puts an
// image's left edge at that fraction of the leftover width, as scene.js does.
const pct = (f) => `${+(f * 100).toFixed(4)}%`;
function background(layers, s) {
  const size = (L) => `${L.w * s}px ${H * s}px`;
  return [...layers]
    .reverse()
    .map((L) => `url("/scene/${L.id}.png") ${L.tile ? "repeat-x left" : `no-repeat ${pct(L.at)}`} bottom / ${size(L)}`)
    .join(",\n    ");
}
function rules(s) {
  return scenes
    .map(({ path, layers }) => {
      const sel = path === null ? ".scene" : `.scene[data-path=${JSON.stringify(path)}]`;
      const height = path === null ? `\n  height: ${H * s}px;` : "";
      return `${sel} {${height}\n  background:\n    ${background(layers, s)};\n}`;
    })
    .join("\n");
}
const indent = (css) => css.replace(/^/gm, "  ");

writeFileSync(
  new URL("scene.css", dir),
  `/* Generated by scripts/scene/render.mjs from static/js/scene/; do not edit. */
.scene {
  overflow: hidden;
  image-rendering: pixelated;
}
.scene canvas {
  display: block;
  image-rendering: pixelated;
}
${rules(SCALE)}
@media (max-width: ${NARROW_MAX}px) {
${indent(rules(NARROW_SCALE))}
}
/* With JS on, canvas.js draws the page's own scene instead. */
.js .scene,
.js .scene[data-path] {
  background: none;
}
`,
);
